"""Import the approved, byte-verified widget and icon subset from a metin2-ui-egui ZIP.

Developer-only regeneration tool: requires Pillow. Runtime embeds one shared atlas.
No recognition captures or gameplay data are imported.
"""
import argparse
import hashlib
import io
import json
from pathlib import Path
import zipfile

STYLES = (
    "board", "thinboard", "titlebar", "button_large", "button_big",
    "close_button", "minimize_button", "tab_large", "gauge_blue",
    "bevel_panel", "listbox", "scrollbar", "scroll_up", "scroll_down",
)
SKILL_RANGES = ((1, 5), (16, 20), (31, 35), (46, 50), (61, 66), (76, 81), (91, 96), (106, 111))
CLASS_IDS = ("warrior", "assassin", "sura", "shaman")
ICON_IDS = (
    "utility/quickbar/mouseattack1", "utility/quickbar/mouseauto1",
    "utility/quickbar/mousecamera1", "utility/quickbar/mouseskill1",
    "utility/quickbar/system1", "utility/common/money", "utility/common/check",
    "utility/party/time", "utility/guild/refresh1", "utility/guild/notice",
    "item/70038", "skill/130",
)


def checked(condition, message):
    if not condition:
        raise ValueError(message)


def load_display_catalog(path):
    """One maintained English display catalog feeds both embedded output formats."""
    display = json.loads(path.read_text(encoding="utf-8"))
    checked(display["language"] == "en", "Display catalog must use English")
    checked([item["id"] for item in display["classes"]] == list(CLASS_IDS), "Display class identity/order changed")
    for index, item in enumerate(display["classes"]):
        checked(bool(item["name"].strip()) and item["name"].isascii(),
                f"Invalid English class label: {item['id']}")
        expected = [n for start, end in SKILL_RANGES[index * 2:index * 2 + 2]
                    for n in range(start, end + 1)]
        checked([skill["id"] for skill in item["skills"]] == expected,
                f"Display catalog must preserve every base skill ID and order: {item['id']}")
        for skill in item["skills"]:
            checked(bool(skill["name"].strip()) and skill["name"].isascii(),
                    f"Invalid English skill label: {skill['id']}")
            checked(skill["source_page"].startswith("https://en-wiki.metin2.gameforge.com/index.php/"),
                    f"Missing official English source: {skill['id']}")
    return display


def english_icons(icons, display):
    labels = {f"skill/{skill['id']}": (skill["name"], "official_english_gameforge_wiki")
              for item in display["classes"] for skill in item["skills"]}
    labels.update({key: (value, "application_english_ui")
                   for key, value in display["icon_labels"].items()})
    for item in display["classes"]:
        for suffix, gender in (("m", "Male"), ("w", "Female")):
            labels[f"portraits/{item['id']}_{suffix}"] = (f"{item['name']} ({gender})", "application_english_ui")
    for key, (label, origin) in labels.items():
        checked(key in icons, f"Display label has no imported icon: {key}")
        icon = icons[key]
        icon["source_label"] = icon["label"]
        icon["source_label_origin"] = icon["label_origin"]
        icon["label"] = label
        icon["label_origin"] = origin


def rust_catalog(display, icons):
    quote = json.dumps
    lines = ["// @generated by tools/import-ui-skin.py from catalog.json; do not edit.",
             "pub const CLASSES: [SkillClass; 4] = ["]
    for item in display["classes"]:
        checked(item["portrait"] in {icon["region"] for icon in icons.values()},
                f"Display class portrait was not imported: {item['id']}")
        lines.extend(["    SkillClass {", f"        id: {quote(item['id'])},",
                      f"        name: {quote(item['name'])},", f"        portrait: {quote(item['portrait'])},",
                      "        skills: &["])
        for skill in item["skills"]:
            region = icons[f"skill/{skill['id']}"]["region"]
            lines.append(f"            entry({skill['id']}, {quote(skill['name'])}, {quote(region)}),")
        lines.extend(["        ],", "    },"])
    lines.extend(["];", ""])
    return "\n".join(lines).encode("utf-8")


def main():
    # Metadata validation/tests require only the standard library; Pillow is
    # needed solely for developer regeneration and verification of source art.
    from PIL import Image

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path)
    parser.add_argument("--check", action="store_true", help="Verify embedded outputs match the source without writing files")
    args = parser.parse_args()
    out = Path(__file__).resolve().parents[1] / "crates/metin-desktop/assets/metin-ui"
    display = load_display_catalog(out / "catalog.json")
    with zipfile.ZipFile(args.archive) as archive:
        manifest_bytes = archive.read("metin2-ui-egui/manifest.json")
        catalog_bytes = archive.read("metin2-ui-egui/icons.json")
        original = json.loads(manifest_bytes)
        catalog = json.loads(catalog_bytes)
        icon_ids = set(ICON_IDS)
        icon_ids.update(f"skill/{n}" for start, end in SKILL_RANGES for n in range(start, end + 1))
        icon_ids.update(key for key, icon in catalog["icons"].items() if icon["category"] == "portraits")
        # Keep source identity/provenance, but only the chosen base image.
        icons = {
            key: {field: value for field, value in catalog["icons"][key].items()
                  if field not in ("variants", "variant_note")}
            for key in sorted(icon_ids)
        }
        english_icons(icons, display)
        names = {"public/slot_base", "pattern/horsestate/00", "pattern/horsestate/13", "pattern/horsestate/33"}
        names.update(icon["region"] for icon in icons.values())
        styles = {key: original["styles"][key] for key in STYLES}
        for style in styles.values():
            names.update(style.get("parts", {}).values())
            names.update(style.get("states", {}).values())
            names.update(style.get("thumb_parts", {}).values())
            if "fill_region" in style:
                names.add(style["fill_region"])
        atlas_names = {original["regions"][name]["atlas"] for name in names}
        images, sources = {}, {}
        for name in sorted(atlas_names):
            atlas = original["atlases"][name]
            data = archive.read("metin2-ui-egui/" + atlas["file"])
            checked(hashlib.sha256(data).hexdigest() == atlas["sha256"], f"Atlas SHA256 mismatch: {name}")
            image = Image.open(io.BytesIO(data)).convert("RGBA")
            checked(list(image.size) == atlas["size_px"], f"Atlas dimensions mismatch: {name}")
            images[name] = image
            sources[name] = atlas
    # Deterministic shelves with a two-pixel transparent gutter on every side.
    packed = Image.new("RGBA", (512, 2048))
    regions = {}
    x = y = row_height = 2
    for name in sorted(names, key=lambda key: (-original["regions"][key]["rect_xywh_px"][3], key)):
        region = original["regions"][name]
        image = images[region["atlas"]]
        sx, sy, width, height = region["rect_xywh_px"]
        checked(width > 0 and height > 0 and sx >= 0 and sy >= 0 and sx + width <= image.width and sy + height <= image.height, f"Invalid source region: {name}")
        pixels = image.crop((sx, sy, sx + width, sy + height))
        checked(hashlib.sha256(pixels.tobytes()).hexdigest() == region["rgba_sha256"], f"Region RGBA mismatch: {name}")
        if x + width + 2 > packed.width:
            x, y, row_height = 2, y + row_height + 4, 0
        checked(width + 4 <= packed.width and y + height + 2 <= packed.height, f"Subset does not fit: {name}")
        packed.paste(pixels, (x, y))
        regions[name] = {
            "rect": [x, y, width, height], "rgba_sha256": region["rgba_sha256"],
            "source_atlas": region["atlas"], "source_rect": region["rect_xywh_px"],
            "sources": region.get("sources", []),
        }
        x += width + 4
        row_height = max(row_height, height)
    height = 1 << (y + row_height + 1).bit_length()
    packed = packed.crop((0, 0, 512, height))
    png = io.BytesIO()
    packed.save(png, format="PNG", optimize=True)
    manifest = {
        "size": list(packed.size), "regions": dict(sorted(regions.items())), "styles": styles,
        "icons": icons, "source_atlases": sources,
        "source_manifest_sha256": hashlib.sha256(manifest_bytes).hexdigest(),
        "source_catalog_sha256": hashlib.sha256(catalog_bytes).hexdigest(),
        "source_identity": original["source_identity"],
        "application_variants": "Wide buttons preserve native-height end caps and tile their center. Disabled sprites are dimmed by the application. One fixed Metin appearance; original RGBA artwork remains unchanged. Unknown mounting adds a question mark as text. Class skill art uses only original base grade images and is presentation-only.",
    }
    outputs = {
        "widgets.png": png.getvalue(),
        "manifest.json": (json.dumps(manifest, indent=2, ensure_ascii=False) + "\n").encode("utf-8"),
        "catalog.rs": rust_catalog(display, icons),
    }
    if args.check:
        for name, data in outputs.items():
            checked((out / name).is_file() and (out / name).read_bytes() == data, f"Embedded output differs from verified source: {name}")
    else:
        out.mkdir(parents=True, exist_ok=True)
        for name, data in outputs.items():
            (out / name).write_bytes(data)
    print(f"{'Verified' if args.check else 'Imported'} {len(regions)} regions from {len(images)} source atlases, {packed.width}x{packed.height}, {len(outputs['widgets.png'])} bytes")


if __name__ == "__main__":
    main()
